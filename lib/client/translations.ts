const patterns: [RegExp, string][] = [
  [/^(\d+) file siap diunduh\.$/, "$1 file(s) ready to download."],
  [
    /^Menyiapkan unduhan (.+)\. Tunggu sebentar sebelum memilih file lain\.$/,
    "Preparing $1 for download. Please wait before choosing another file.",
  ],
  [/^Maks\. total (\d+) MB$/, "Up to $1 MB total"],
  [/^(\d+) file · (.+)$/, "$1 file(s) · $2"],
  [/^(.+) tersisa$/, "$1 left"],
  [/^Detail file (.+)$/, "File details: $1"],
  [/^Unduh (.+)$/, "Download $1"],
  [/^Progres (.+)$/, "Progress for $1"],
  [/^Hapus (.+)$/, "Remove $1"],
  [/^(.+) dari (.+)$/, "$1 of $2"],
  [
    /^Terlalu banyak percobaan\. Coba lagi dalam (\d+) detik\.$/,
    "Too many attempts. Try again in $1 seconds.",
  ],
  [
    /^Layanan sedang ramai\. Coba lagi dalam (\d+) detik\.$/,
    "The service is busy. Try again in $1 seconds.",
  ],
];

export function translateText(text: string, language: "en" | "id") {
  if (language === "id" || !text) return text;
  if (english[text]) return english[text];
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(text)) {
      const result = text.replace(pattern, replacement);
      return result
        .replace(/\b1 file\(s\)/g, "1 file")
        .replace(/file\(s\)/g, "files");
    }
  }
  return text;
}
